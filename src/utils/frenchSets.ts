export function frenchCardImageUrl(
  setId: string,
  cardNumber: string,
  quality: 'low' | 'high' = 'low',
): string | null {
  const meta = FRENCH_SETS[setId]
  if (!meta?.assetBase || !cardNumber) return null
  const clean = cardNumber.trim()
  if (!clean) return null
  const localId = meta.pad3 && /^\d{1,2}$/.test(clean) ? clean.padStart(3, '0') : clean
  return `${meta.assetBase}/${encodeURIComponent(localId)}/${quality}.webp`
}

export interface TcgdexFrenchCardInfo {
  id: string
  localId: string
  name: string
  imageSmall: string
  imageLarge: string
}

const tcgdexSetCache = new Map<string, Promise<Map<string, TcgdexFrenchCardInfo> | null>>()

export function normalizeCardNum(n: string): string {
  const trimmed = n.trim().toUpperCase()
  if (/^\d+$/.test(trimmed)) return String(Number.parseInt(trimmed, 10))
  return trimmed
}

/**
 * Charge les vrais noms et images français officiels d’une série depuis TCGdex FR (mis en cache).
 */
export function fetchTcgdexFrenchSet(
  setId: string,
): Promise<Map<string, TcgdexFrenchCardInfo> | null> {
  const meta = FRENCH_SETS[setId]
  if (!meta) return Promise.resolve(null)
  const cached = tcgdexSetCache.get(setId)
  if (cached) return cached

  const req = fetch(`https://api.tcgdex.net/v2/fr/sets/${encodeURIComponent(meta.tcgdexId)}`)
    .then((res) => (res.ok ? res.json() : null))
    .then(
      (
        json: { cards?: { id: string; localId: string; name: string; image?: string }[] } | null,
      ) => {
        if (!json?.cards?.length) return null
        const map = new Map<string, TcgdexFrenchCardInfo>()
        for (const c of json.cards) {
          const base =
            c.image || (meta.assetBase ? `${meta.assetBase}/${encodeURIComponent(c.localId)}` : '')
          const info: TcgdexFrenchCardInfo = {
            id: c.id,
            localId: c.localId,
            name: c.name,
            imageSmall: base ? `${base}/low.webp` : '',
            imageLarge: base ? `${base}/high.webp` : '',
          }
          map.set(normalizeCardNum(c.localId), info)
        }
        return map
      },
    )
    .catch(() => null)

  tcgdexSetCache.set(setId, req)
  return req
}

